/**
 * 글 주소 조각 (IDE-023)
 *
 * `/blog/<슬러그>` 의 뒷부분이다. 한 번 세상에 나가면 바꾸기 어려운 값이라
 * — 검색엔진이 그 주소로 색인하고 링크가 그 주소로 돌아다닌다 — 만들 때
 * 규칙을 좁게 잡는다.
 *
 * **한글을 지운다.** 사용자가 한국어로 글을 쓰므로 제목에서 슬러그를 뽑으면
 * 대부분 한글이 되는데, 주소에 들어가면 퍼센트 인코딩으로 부풀어 카톡·문자에
 * 붙였을 때 알아볼 수 없는 문자열이 된다. 대신 제목이 전부 한글이면 슬러그를
 * 뽑을 수 없으므로, 그때는 **비워서 돌려주고 사람이 직접 적게 한다.**
 *
 * `import 'server-only'` 를 붙이지 않는다 — 관리자 화면이 브라우저에서 미리
 * 보여 줄 값이다.
 */

/** 주소에 쓸 수 있는 최대 길이. 넘으면 자른다. */
const MAX = 80;

/**
 * 아무 글자나 받아 쓸 수 있는 슬러그로 접는다. 못 만들면 빈 문자열이다.
 *
 * 이미 슬러그인 값을 다시 넣어도 같은 값이 나온다(멱등) — 편집 화면이 저장할
 * 때마다 한 번씩 더 접는데, 그때 값이 흔들리면 주소가 저 혼자 바뀐다.
 */
export function toSlug(raw: string): string {
  return (
    raw
      .normalize('NFKD')
      // 발음 구별 기호를 떼어 `é` → `e` 로 만든다. 앞의 NFKD 와 짝이다.
      .replace(/[̀-ͯ]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, MAX)
      .replace(/-+$/, '')
  );
}

/** 저장해도 되는 슬러그인가. 사람이 직접 적은 값을 받는 자리에서 본다. */
export const isValidSlug = (value: string): boolean =>
  value.length > 0 && value.length <= MAX && toSlug(value) === value;
