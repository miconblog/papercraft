/**
 * 사진 크기 한도 — 한 곳에서 정한다 (IDE-028)
 *
 * 두 군데가 같은 값을 봐야 한다.
 *
 * 1. **업로드 검사**(`images.ts`) — 이보다 크면 받지 않는다.
 * 2. **서버 액션 본문 한도**(`next.config.ts`) — Next 는 기본 1MB 다.
 *
 * 갈라져 있었다. 1번을 8MB 로 두고 2번을 그대로 두는 바람에, 폰 사진을 넣으면
 * `Body exceeded 1 MB limit` 로 **저장 자체가 터졌다**(2026-09-09 사용자 신고).
 * 사진만 못 넣는 것이 아니라 쓰던 글까지 함께 못 넘어간다.
 *
 * **여기에는 아무것도 import 하지 않는다** — `next.config.ts` 가 읽는 파일이라
 * 무거운 것이 딸려 오면 안 되고, 브라우저 쪽 컴포넌트도 같은 값을 본다.
 */

/** 사진 한 장의 최대 크기. 폰 원본 한 장이 넉넉히 들어간다. */
export const PHOTO_MAX_BYTES = 8 * 1024 * 1024;

/**
 * 서버 액션이 받는 본문 한도.
 *
 * 사진 하나만 오는 것이 아니다 — **쓰던 글 전체가 같은 폼에 실려 온다**
 * (`IDE-023` 이 정한 "어느 버튼을 눌러도 먼저 저장된다"). 거기에
 * `multipart/form-data` 의 경계·머리말이 더 붙으므로 넉넉히 둔다.
 */
export const ACTION_BODY_LIMIT = `${PHOTO_MAX_BYTES / 1024 / 1024 + 4}mb`;
